const {openSettings, closeSettings} = require('./ui.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
  const context = await browser.newContext({viewport:{width:390,height:844}});
  const page = await context.newPage(); const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:8769/');
  await page.locator('#days .day:not(.outside)').first().click();
  await page.locator('#daily-note').waitFor();
  await page.waitForFunction(()=>!document.querySelector('#daily-note').disabled);
  const hash = new URL(page.url()).hash;
  await page.locator('#daily-note').fill('A calm day. 中文 <script>not markup</script>');
  await page.locator('#save-note').click();
  await page.waitForFunction(()=>document.querySelector('#note-status').textContent==='Saved on this device.');
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#daily-note').disabled);
  assert.equal(await page.locator('#daily-note').inputValue(),'A calm day. 中文 <script>not markup</script>');
  await page.locator('#back-to-calendar').click();
  await page.locator('#calendar-page').waitFor({state:'visible'});
  assert.equal(await page.locator('.has-note').count(),1);
  await openSettings(page);
  await page.locator('summary').click();
  const download = page.waitForEvent('download'); await page.locator('#export-notes').click();
  const file=await download; const backup=JSON.parse(require('node:fs').readFileSync(await file.path(),'utf8'));
  assert.equal(backup.notes.length,1);
  await closeSettings(page);
  await page.locator('.has-note').click();
  page.once('dialog',d=>d.accept()); await page.locator('#delete-note').click();
  await page.waitForFunction(()=>document.querySelector('#daily-note').value==='');
  await openSettings(page);
  await page.locator('#import-notes').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await page.locator('#confirm-import').click();
  await page.waitForFunction(()=>document.querySelector('#daily-note').value.includes('A calm day.'));
  await page.locator('#import-notes').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...backup,notes:[...backup.notes,...backup.notes]}))});
  await page.waitForFunction(()=>document.querySelector('#backup-status').textContent.includes('invalid or duplicate'));
  assert(await page.locator('#import-preview').isHidden());
  await page.locator('#install-app').click(); assert(await page.locator('#install-help').isVisible());
  await page.locator('#install-help button').click();
  await closeSettings(page);
  await page.evaluate(async()=>{ await navigator.serviceWorker.ready; });
  await page.reload();
  await page.waitForFunction(()=>navigator.serviceWorker.controller);
  await context.setOffline(true); await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#daily-note').disabled);
  assert((await page.locator('#daily-note').inputValue()).includes('A calm day.'));
  await page.locator('#language-choice').selectOption('ru');
  assert.equal(await page.locator('#note-title').textContent(),'Заметка за день');
  assert((await page.locator('#daily-note').inputValue()).includes('A calm day.'));
  await page.locator('#language-choice').selectOption('en');
  assert.equal(new URL(page.url()).hash,hash);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log('Passed: save/reload, note indicators, export/delete/import, invalid import, install help, offline reload, mobile fit.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
